class Command(BaseCommand):
    help = "ایجاد استان‌ها و شهرهای ایران"

    def handle(self, *args, **options):
        province_count = 0
        city_count = 0

        self.stdout.write("شروع وارد کردن اطلاعات استان‌ها و شهرها...")

        for province_name, cities in IRAN_LOCATIONS.items():
            province, created = Province.objects.get_or_create(
                name=province_name,
                defaults={
                    "name_en": "",
                    "code": "",
                },
            )

            if created:
                province_count += 1
                self.stdout.write(
                    self.style.SUCCESS(
                        f"استان ایجاد شد: {province_name}"
                    )
                )

            for city_name in cities:
                city, created = City.objects.get_or_create(
                    province=province,
                    name=city_name,
                    defaults={
                        "name_en": "",
                        "code": "",
                    },
                )

                if created:
                    city_count += 1

        self.stdout.write("")
        self.stdout.write(
            self.style.SUCCESS(
                f"تعداد استان‌های جدید: {province_count}"
            )
        )
        self.stdout.write(
            self.style.SUCCESS(
                f"تعداد شهرهای جدید: {city_count}"
            )
        )

        self.stdout.write(
            self.style.SUCCESS(
                "اطلاعات استان‌ها و شهرها با موفقیت ثبت شد."
            )
        )